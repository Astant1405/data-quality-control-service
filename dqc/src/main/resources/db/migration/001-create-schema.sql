CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    parent_id BIGINT,
    CONSTRAINT chk_department_not_self CHECK ((parent_id IS NULL) OR (parent_id <> id))
);

CREATE TABLE goal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    owner_id VARCHAR(100),
    parent_goal_id BIGINT,
    title VARCHAR(500) NOT NULL,
    description TEXT,
    status VARCHAR(30) NOT NULL,
    due_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_goal_not_self_parent CHECK ((parent_goal_id IS NULL) OR (parent_goal_id <> id)),
    CONSTRAINT chk_goal_status CHECK (status IN ('DRAFT', 'ACTIVE', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE key_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id BIGINT NOT NULL,
    title VARCHAR(500) NOT NULL,
    target_value NUMERIC(15,2),
    actual_value NUMERIC(15,2),
    weight NUMERIC(5,2) NOT NULL,
    actual_updated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_kr_weight_nonnegative CHECK (weight >= 0)
);

CREATE TABLE kkd_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    severity VARCHAR(20) NOT NULL,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT chk_rule_severity CHECK (severity IN ('critical', 'major', 'minor'))
);

CREATE TABLE kkd_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_date DATE NOT NULL,
    compared_to_run_id BIGINT,
    status VARCHAR(20) DEFAULT 'RUNNING' NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    run_code VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT chk_run_not_self_compare CHECK ((compared_to_run_id IS NULL) OR (compared_to_run_id <> id)),
    CONSTRAINT chk_run_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED'))
);

CREATE TABLE kkd_issue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    rule_id BIGINT NOT NULL,
    goal_id BIGINT,
    key_result_id BIGINT,
    severity VARCHAR(20) NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_issue_object CHECK ((goal_id IS NOT NULL AND key_result_id IS NULL) OR (goal_id IS NULL AND key_result_id IS NOT NULL)),
    CONSTRAINT chk_issue_severity CHECK (severity IN ('critical', 'major', 'minor'))
);

CREATE TABLE kkd_metric_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    metric_key VARCHAR(50) NOT NULL,
    metric_value NUMERIC(10,2) NOT NULL,
    CONSTRAINT uq_metric_run_unit_key UNIQUE (run_id, unit_id, metric_key)
);


